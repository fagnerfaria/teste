/**
 * Rebuild redistributable snapshots from inspected, pinned source checkouts.
 * Usage: node scripts/import-curriculum.mjs /path/to/ubl /path/to/aprenda
 * Never copies linked videos/books, third-party content or executable MDX.
 */
import {readFile,writeFile,mkdir,readdir,rm} from 'node:fs/promises';
import {execFileSync} from 'node:child_process';
import {resolve,relative,dirname} from 'node:path';
import {createHash} from 'node:crypto';
const sources=[
 {id:'ubl',repository:'Universidade-Livre/ciencia-da-computacao',revision:'b995c118fdb3929412004ee041a25c77cb0aa997',license:'MIT',licenseUrl:'https://opensource.org/license/mit',author:'Universidade Brasileira Livre e colaboradores',dir:process.argv[2],eligible:p=>p.endsWith('.md')},
 {id:'aprenda-community',repository:'lucianodiisouza/aprenda-community',revision:'a3fd6b8b13345093e4a68afa3c3bad47cf822e0e',license:'CC-BY-SA-4.0',licenseUrl:'https://creativecommons.org/licenses/by-sa/4.0/',author:'Luciano dii Souza e comunidade Aprenda',dir:process.argv[3],eligible:p=>p.startsWith('roadmaps/')&&(/\.mdx?$/.test(p)||p.endsWith('/roadmap.json'))},
];
if(sources.some(s=>!s.dir))throw new Error('Informe os dois checkouts locais (UBL e Aprenda).');
const output=resolve(new URL('../public/content',import.meta.url).pathname);
const manifest={version:1,capturedAt:'2026-11-02',sources:{},documents:[],collections:[]};
async function walk(dir,base=dir){
 let out=[];
 for(const entry of await readdir(dir,{withFileTypes:true})){
  if(entry.name.startsWith('.'))continue;
  const path=resolve(dir,entry.name);
  if(entry.isDirectory())out.push(...await walk(path,base));
  else if(entry.isFile())out.push({absolute:path,path:relative(base,path).split('\\').join('/')});
 }
 return out;
}
// Validate every source before changing the existing snapshot.
for(const s of sources){
 s.dir=resolve(s.dir);
 const actual=execFileSync('git',['rev-parse','HEAD'],{cwd:s.dir,encoding:'utf8'}).trim();
 if(actual!==s.revision)throw new Error(`${s.id}: expected ${s.revision}; received ${actual}`);
 const dirty=execFileSync('git',['status','--porcelain'],{cwd:s.dir,encoding:'utf8'}).trim();
 if(dirty)throw new Error(`${s.id}: checkout must be clean`);
 s.licenseText=await readFile(resolve(s.dir,'LICENSE'),'utf8');
 if(s.id==='ubl'&&!s.licenseText.includes('MIT License'))throw new Error('UBL license changed');
 if(s.id==='aprenda-community'&&!s.licenseText.includes('CC BY-SA 4.0'))throw new Error('Aprenda content license changed');
}
await mkdir(output,{recursive:true});
for(const s of sources){
 await rm(resolve(output,s.id),{recursive:true,force:true});
 manifest.sources[s.id]={repository:s.repository,revision:s.revision,license:s.license,licenseUrl:s.licenseUrl,author:s.author,licenseText:s.licenseText,modifications:'Snapshot literal dos arquivos; leitor apresenta MDX como dados e adapta somente a visualização. As adaptações de apresentação do conteúdo Aprenda permanecem CC BY-SA 4.0.'};
 for(const file of (await walk(s.dir)).filter(f=>s.eligible(f.path)).sort((a,b)=>a.path.localeCompare(b.path))){
  const body=await readFile(file.absolute,'utf8');
  const target=resolve(output,s.id,file.path);
  await mkdir(dirname(target),{recursive:true});
  await writeFile(target,body);
  const encoded=file.path.split('/').map(encodeURIComponent).join('/');
  const title=body.match(/^title:\s*["']?([^\n"']+)/m)?.[1]||body.match(/^#\s+(.+)/m)?.[1]||file.path.split('/').at(-1).replace(/\.(mdx?|json)$/,'').replace(/[-_]/g,' ');
  manifest.documents.push({sourceId:s.id,path:file.path,title,collection:s.id==='aprenda-community'?file.path.split('/')[1]:'ciencia-da-computacao',url:`/content/${s.id}/${encoded}`,sha256:createHash('sha256').update(body).digest('hex'),original:`https://github.com/${s.repository}/blob/${s.revision}/${encoded}`,bytes:Buffer.byteLength(body)});
  if(file.path.endsWith('/roadmap.json')){
   const map=JSON.parse(body);
   manifest.collections.push({sourceId:s.id,id:map.slug,title:map.title,description:map.description,difficulty:map.difficulty,skills:map.skills||[],nodes:map.nodes.map(n=>({id:n.id,title:n.title,children:n.children||[],path:`roadmaps/${map.slug}/nodes/${n.id}.mdx`}))});
  }
 }
}
await writeFile(resolve(output,'manifest.json'),JSON.stringify(manifest,null,2)+'\n');
await writeFile(new URL('../src/lib/content/snapshot-index.ts',import.meta.url), '// Generated by scripts/import-curriculum.mjs; source documents retain their own licenses.\nexport const SNAPSHOT_DOCUMENTS = '+JSON.stringify(manifest.documents)+' as const;\nexport const SNAPSHOT_COLLECTIONS = '+JSON.stringify(manifest.collections)+' as const;\n');
console.log(`${manifest.documents.length} documents; ${manifest.collections.length} collections. Pinned source revisions and source licenses included.`);
